export function stateNameByCode(code: string): string | undefined {
  return GST_STATE_CODES[code];
}

export function isValidStateCode(code: string): boolean {
  return code in GST_STATE_CODES;
}

export function stateCodeByName(name: string): string | undefined {
  const target = name.trim().toLowerCase();
  for (const [code, n] of Object.entries(GST_STATE_CODES)) {
    if (n.toLowerCase() === target) return code;
  }
  return undefined;
}
