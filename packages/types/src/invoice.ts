import { z } from "zod";

export const InvoiceLine = z.object({
  description: z.string(),
  hsnCode: z.string(),
  quantity: z.number(),
  unitPrice: z.number(),
  discount: z.number().default(0),
  taxableValue: z.number(),
  gstRate: z.number(),
  cgst: z.number(),
  sgst: z.number(),
  igst: z.number(),
  cess: z.number().default(0),
  lineTotal: z.number(),
});

export const InvoiceDto = z.object({
  invoiceNumber: z.string(),
  series: z.string(),
  financialYear: z.string(),
  issuedAt: z.string(),
  placeOfSupply: z.string(),
  reverseCharge: z.boolean(),
  seller: z.object({
    gstin: z.string(),
    legalName: z.string(),
    tradeName: z.string().optional(),
    address: z.object({
      line1: z.string(),
      line2: z.string().optional(),
      city: z.string(),
      state: z.string(),
      stateCode: z.string(),
      pincode: z.string(),
      country: z.string(),
    }),
    email: z.string().optional(),
    phone: z.string().optional(),
  }),
  buyer: z.object({
    gstin: z.string().optional(),
    legalName: z.string(),
    billingAddress: z.object({
      line1: z.string(),
      line2: z.string().optional(),
      city: z.string(),
      state: z.string(),
      stateCode: z.string(),
      pincode: z.string(),
      country: z.string(),
    }),
    shippingAddress: z.object({
      line1: z.string(),
      line2: z.string().optional(),
      city: z.string(),
      state: z.string(),
      stateCode: z.string(),
      pincode: z.string(),
      country: z.string(),
    }),
    email: z.string().optional(),
    phone: z.string().optional(),
  }),
  lines: z.array(InvoiceLine),
  totals: z.object({
    subtotal: z.number(),
    totalDiscount: z.number(),
    taxableValue: z.number(),
    cgstTotal: z.number(),
    sgstTotal: z.number(),
    igstTotal: z.number(),
    cessTotal: z.number(),
    roundOff: z.number(),
    grandTotal: z.number(),
  }),
  amountInWords: z.string(),
  irn: z.string().optional(),
  ackNo: z.string().optional(),
  ackDate: z.string().optional(),
  signedQr: z.string().optional(),
});
export type InvoiceDto = z.infer<typeof InvoiceDto>;
